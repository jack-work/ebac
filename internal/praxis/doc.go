package praxis

import (
	"fmt"
	"strings"
)

// GenDoc renders the praxis issue standard from this package: the shapes, an example tree rendered
// by the same functions the sync posts with, and every refusal the validator raises. The standard
// doc is this output; nobody edits it by hand.
func GenDoc() string {
	parent := Issue{
		Number: 1000, Topic: "Example topic", K: 0, N: 2, Status: Split, Assignee: "ours",
		Summary:  "What the whole stack delivers",
		Delivers: "the outcome the stack exists for",
		Children: []Child{
			{Number: 1001, K: 1, Summary: "First piece", Status: InProgress},
			{Number: 1002, K: 2, Summary: "Second piece", Status: Claimed},
		},
	}
	child := Issue{
		Number: 1001, Topic: "Example topic", K: 1, N: 2, Parent: 1000, Status: InProgress, Assignee: "ours",
		Summary:  "First piece",
		Delivers: "one checkable outcome of this piece",
		Contract: "Delivers: one checkable outcome of this piece\nOwner: ours\nStatus: building\nAcceptance:\n- <a statement that is red on revert>",
	}
	done := child
	done.Status, done.PRs = Done, []int{2001}

	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# Praxis issue standard (generated)\n\n")
	w("Generated by `go run ./cmd/praxis-doc` from the ebac package `internal/praxis`; do not edit by hand. ")
	w("A praxis issue is an entity form; GitHub shows what this package renders from it, and the gh-cache sync refuses a form this package's validator refuses.\n\n")
	w("## The form\n\n")
	w("| Key | Meaning |\n|---|---|\n")
	for _, r := range [][2]string{
		{"praxis.topic", "the stack's topic, one line, no brackets"},
		{"praxis.k", "0 for the stack's issue 0, else this piece's place 1..n"},
		{"praxis.n", "how many pieces the stack has (at least 1)"},
		{"praxis.parent", "the parent issue number (required for k >= 1)"},
		{"praxis.summary", "the title's text"},
		{"praxis.delivers", "the one-line outcome"},
		{"praxis.status", "one of " + statusList()},
		{"praxis.assignee", "the GitHub login that holds it"},
		{"praxis.prs[]", "the PRs that fix it"},
		{"praxis.children[]", "an issue 0's pieces (number, k, summary, status)"},
		{"praxis.contract", "optional: the body of its ## Contract section"},
	} {
		w("| `%s` | %s |\n", r[0], r[1])
	}
	w("\n## Shapes\n\n")
	w("- Issue 0: title `[<topic>][0-<n>] <summary>`; body opens with `Delivers:` and lists its pieces under `## Stack` in k order.\n")
	w("- Piece: title `[<topic>][<k>-<n>] <summary>`; body opens with `Part of #<parent>`, `Stack: <k> of <n>`, `Delivers: ...`.\n")
	w("- Deeper tiers repeat the shape under a piece.\n")
	w("- A PR that fixes a piece says `Fixes #<piece>` in its body.\n\n")
	w("## Example tree\n\n")
	section := func(name, text string) { w("### %s\n\n```\n%s\n```\n\n", name, strings.TrimRight(text, "\n")) }
	section("Issue 0 title", Title(parent))
	section("Issue 0 body", Body(parent))
	section("Split comment", SplitComment(parent))
	section("Piece title", Title(child))
	section("Piece body", Body(child))
	section("Claim comment", ClaimComment(child))
	section("Status comment", StatusComment(child))
	section("Done comment", DoneComment(done))
	w("## Refusals\n\nThe sync raises `sync.alarm.praxis.<rule>` on the issue's form and posts nothing.\n\n")
	w("| Rule | Refused when |\n|---|---|\n")
	for _, r := range [][2]Rule{
		{RuleBadTopic, "the topic is empty, has a bracket or a line break"},
		{RuleNOutOfRange, "n < 1"},
		{RuleKOutOfRange, "k < 0 or k > n"},
		{RuleNoParent, "a piece (k >= 1) names no parent"},
		{RuleSelfParent, "an issue names itself as parent"},
		{RuleParentClosed, "the parent is closed"},
		{RuleParentDone, "the parent is done"},
		{RuleEmptySummary, "the summary is empty"},
		{RuleEmptyDelivers, "delivers is empty"},
		{RuleBadStatus, "the status is not one of " + Rule(statusList())},
		{RuleSplitWithoutChildren, "the status is split with no children"},
		{RuleChildOutOfRange, "a child's k is outside 1..n"},
		{RuleDoneWithoutPRs, "done with no PRs (an issue 0 may be done when every child is done)"},
	} {
		w("| `%s` | %s |\n", r[0], r[1])
	}
	return b.String()
}

func statusList() string {
	s := make([]string, len(Statuses))
	for k, v := range Statuses {
		s[k] = "`" + string(v) + "`"
	}
	return strings.Join(s, ", ")
}
